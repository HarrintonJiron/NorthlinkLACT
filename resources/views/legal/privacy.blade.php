        <h1>Política de privacidad de Lácteos Quebar</h1>
        <p class="updated">Última actualización: 3 de noviembre de 2026</p>
        <p>Lácteos Quebar, con soporte tecnológico de Northlink Microsystem, utiliza esta aplicación empresarial para registrar la recolección de leche en rutas autorizadas.</p>

        <h2>Datos tratados</h2>
        <p>La aplicación procesa la identidad y cuenta del operador, identificador técnico del dispositivo, productores asignados, nombre y teléfono de productores, ruta, cantidades de leche, densidad, controles de recepción, fecha y hora, comprobantes impresos y estado de sincronización.</p>

        <h2>Finalidad</h2>
        <p>Los datos se usan exclusivamente para operar las rutas de acopio, emitir comprobantes, mantener registros fuera de línea y sincronizar las entregas con la plataforma administrativa de Lácteos Quebar.</p>

        <h2>Almacenamiento y seguridad</h2>
        <p>La información permanece dentro del almacenamiento privado de la aplicación mientras el equipo está sin conexión; las copias de seguridad externas están deshabilitadas y el token de acceso se protege mediante el almacén criptográfico de Android. Cuando hay conexión autorizada, la información se transmite mediante HTTPS al servidor de la empresa. El acceso requiere una cuenta asignada y cada dispositivo se identifica individualmente.</p>

        <h2>Divulgación y conservación</h2>
        <p>No vendemos información personal ni la utilizamos para publicidad. Los datos se comparten únicamente con personal autorizado y proveedores técnicos necesarios para operar el servicio. En el dispositivo, los acopios sincronizados pueden conservarse hasta 45 días para respaldo operativo; los registros pendientes o en conflicto se conservan hasta su resolución. En el servidor se mantienen durante los periodos operativos, contables y legales aplicables.</p>

        <h2>Contacto y solicitudes</h2>
        <p>Los productores y operadores pueden solicitar acceso, corrección, revisión o eliminación cuando corresponda, comunicándose con la administración de Lácteos Quebar o con Northlink Microsystem mediante <a href="mailto:harrinton7usa@gmail.com">harrinton7usa@gmail.com</a>. Sitio oficial: <a href="https://lact.northlinkni.com">lact.northlinkni.com</a>.</p>
