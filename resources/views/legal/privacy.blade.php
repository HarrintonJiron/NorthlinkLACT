        <h1>Política de privacidad de Lácteos Quebar</h1>
        <p class="updated">Última actualización: 3 de noviembre de 2026</p>
        <p>Lácteos Quebar, con soporte tecnológico de Northlink Microsystem, utiliza esta aplicación empresarial para registrar la recolección de leche en rutas autorizadas.</p>

        <h2>Datos tratados</h2>
        <p>La aplicación procesa la identidad del operador, productores asignados, ruta, cantidades de leche, controles de recepción, fecha y hora, estado de sincronización e identificador técnico del dispositivo.</p>

        <h2>Finalidad</h2>
        <p>Los datos se usan exclusivamente para operar las rutas de acopio, emitir comprobantes, mantener registros fuera de línea y sincronizar las entregas con la plataforma administrativa de Lácteos Quebar.</p>

        <h2>Almacenamiento y seguridad</h2>
        <p>La información puede permanecer cifrada o protegida localmente mientras el equipo está sin conexión. Cuando hay conexión autorizada, se transmite mediante HTTPS al servidor de la empresa. El acceso requiere una cuenta asignada y los dispositivos se vinculan individualmente.</p>

        <h2>Divulgación y conservación</h2>
        <p>No vendemos información personal. Los datos se comparten únicamente con personal autorizado y proveedores técnicos necesarios para operar el servicio. Se conservan conforme a las necesidades operativas, contables y legales de la empresa.</p>

        <h2>Contacto y solicitudes</h2>
        <p>Los productores y operadores pueden solicitar acceso, corrección o revisión de sus datos comunicándose con la administración de Lácteos Quebar o con Northlink Microsystem.</p>
